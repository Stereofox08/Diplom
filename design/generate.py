#!/usr/bin/env python3
"""Generate visual adapters from one source. No product behavior or database changes."""
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
t = json.loads((ROOT / 'design/tokens.json').read_text())
check = '--check' in sys.argv
native = t[t.get('defaultTheme', 'dark')]
outputs = {}
outputs['brand-icon.svg'] = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" rx="6" fill="'+native['accent']+'"/><path d="M8 8h8v8H8z" fill="'+native['inverse']+'"/></svg>\n'
alias = {'bg':'bg','bgSoft':'bg-soft','surface':'surface','panel':'surface-2','raised':'surface-3','hover':'surface-hover','border':'border','borderStrong':'border-strong','text':'text','text2':'text-2','muted':'text-3','inverse':'text-inv','accent':'accent','accent2':'accent-2','accent3':'accent-3','success':'ok','warning':'warn','danger':'danger','info':'info','overlay':'overlay'}
css = '/* Generated by design/generate.py. Edit design/tokens.json. */\n'
for font in t['fonts']:
    css += '@font-face { font-family: "'+font['name']+'"; src: url("fonts/'+font['file']+'") format("truetype"); font-weight: 100 900; font-display: swap; }\n'
for mode, selector in [('dark', ':root, [data-theme="dark"]'), ('light', '[data-theme="light"]')]:
    css += selector+' {\n'
    for key, value in t[mode].items(): css += '  --'+alias[key]+': '+value+';\n'
    css += '  --brand-primary: '+t[mode]['accent']+';\n  --brand-on-primary: '+t[mode]['inverse']+';\n'
    css += '  --grad-accent: linear-gradient(110deg, var(--accent), var(--accent));\n  --grad-mesh: none;\n  --glow: 0 0 0 3px color-mix(in srgb, var(--accent) 24%, transparent);\n}\n'
css += ':root {\n  --font-sans: "'+t['typography']['body']+'", "Segoe UI", Arial, sans-serif;\n  --font-display: "'+t['typography']['display']+'", "'+t['typography']['body']+'", sans-serif;\n  --font-mono: "SFMono-Regular", Consolas, monospace;\n'
for key, name in [('control','control'),('card','card'),('small','badge'),('denseCard','dense-card'),('table','table')]:
    css += '  --brand-'+name+'-radius: '+str(t['radius'][key])+'px;\n'
css += '  --r-xs: 6px; --r-sm: var(--brand-control-radius); --r-md: var(--brand-dense-card-radius); --r-lg: var(--brand-card-radius); --r-xl: '+str(t['radius']['large'])+'px; --r-pill: var(--brand-control-radius);\n'
css += '  --t-fast: '+str(t['motion']['fast'])+'ms ease; --t: '+str(t['motion']['normal'])+'ms ease;\n}\n'
outputs['css/brand-tokens.css'] = css
colors = {'BG':'bg','SURFACE':'surface','PANEL':'panel','RAISED':'raised','BORDER':'border','TEXT':'text','MUTED':'muted','ACCENT':'accent','GREEN':'success','RED':'danger'}
java = '// Generated by design/generate.py. Do not edit.\npackage kz.bytestore.shop;\nfinal class BrandTokens {\n'
for name, key in colors.items():
    java += '  static final int '+name+' = 0xFF'+native[key][1:]+';\n'
    java += '  static final int DARK_'+name+' = 0xFF'+t['dark'][key][1:]+';\n'
java += '  static final int ON_PRIMARY = 0xFF'+native['inverse'][1:]+', DARK_ON_PRIMARY = 0xFF'+t['dark']['inverse'][1:]+';\n'
for role in ['body','display']:
    font = next(f for f in t['fonts'] if f['name'] == t['typography'][role])
    java += '  static final String '+role.upper()+'_FONT = '+json.dumps('fonts/'+font['file'])+';\n'
java += '  static final int CONTROL_HEIGHT = '+str(t['spacing']['mobileControlHeight'])+';\n'
java += '  static final int CONTROL_RADIUS = '+str(t['radius']['control'])+', CARD_RADIUS = '+str(t['radius']['card'])+';\n}\n'
outputs['android-store/app/src/main/java/kz/bytestore/shop/BrandTokens.java'] = java
outputs['android-store/app/src/main/res/values/brand_colors.xml'] = '<!-- Generated by design/generate.py -->\n<resources>\n'+''.join('  <color name="brand_'+k+'">'+native[v]+'</color>\n' for k,v in [('background','bg'),('primary','accent'),('text','text'),('surface','surface')])+'</resources>\n'
outputs['android-store/app/src/main/res/values/brand_dark_colors.xml'] = '<!-- Generated by design/generate.py -->\n<resources>\n'+''.join('  <color name="brand_dark_'+k+'">'+t['dark'][v]+'</color>\n' for k,v in [('background','bg'),('primary','accent'),('text','text'),('surface','surface')])+'</resources>\n'
outputs['windows-admin/app/theme.json'] = json.dumps({'background':native['bg']},indent=2)+'\n'
hexcolor = native['bg'].lstrip('#')
channels = [int(hexcolor[i:i+2],16)/255 for i in [0,2,4]]
outputs['macos-admin/Sources/BrandTheme.swift'] = '// Generated by design/generate.py.\nimport AppKit\nenum BrandTheme {\n    static let background = NSColor(srgbRed: %.8f, green: %.8f, blue: %.8f, alpha: 1)\n}\n'%tuple(channels)
for name in ['ic_brand_mark.xml','ic_launcher.xml']:
    value = (ROOT/'design/templates'/name).read_text()
    for role in ['accent','inverse','bg']: value = value.replace('@'+role+'@',native[role])
    outputs['android-store/app/src/main/res/drawable/'+name] = value
errors = []
for rel, value in outputs.items():
    p = ROOT/rel
    if check:
        if not p.exists() or p.read_text() != value: errors.append(rel)
    else:
        p.parent.mkdir(parents=True,exist_ok=True)
        p.write_text(value)
for font in t['fonts']:
    for name in [font['file'],font['license']]:
        src = ROOT/'css/fonts'/name
        dest = ROOT/'android-store/app/src/main/assets/fonts'/name
        if check:
            if not src.exists() or not dest.exists() or src.read_bytes() != dest.read_bytes(): errors.append(str(dest.relative_to(ROOT)))
        else:
            dest.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(src,dest)
if errors:
    print('Token/font drift: '+', '.join(errors))
    sys.exit(1)
print('PASS: shared visual tokens and fonts '+('match all platform adapters' if check else 'generated for web, Android, macOS and Windows'))
